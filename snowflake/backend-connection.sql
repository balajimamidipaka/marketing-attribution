    s.SPEND_DATE,
    s.SPEND_AMOUNT
FROM MARKETING_DB.RAW.CAMPAIGN_SPEND_RAW s
LEFT JOIN MARKETING_DB.RAW.CAMPAIGNS_RAW c
    ON s.CAMPAIGN_ID = c.CAMPAIGN_ID
WHERE c.CAMPAIGN_ID IS NULL;

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        SOURCE_CHANNEL IS NULL
        OR TRIM(SOURCE_CHANNEL) = ''
    ) AS MISSING_SOURCE_CHANNEL,

    COUNT_IF(
        STANDARD_CHANNEL IS NULL
        OR TRIM(STANDARD_CHANNEL) = ''
    ) AS MISSING_STANDARD_CHANNEL,

    COUNT_IF(
        SOURCE_PLATFORM IS NULL
        OR TRIM(SOURCE_PLATFORM) = ''
    ) AS MISSING_SOURCE_PLATFORM

FROM MARKETING_DB.RAW.CHANNEL_MAPPING_RAW;

SELECT
    LOWER(TRIM(SOURCE_CHANNEL)) AS NORMALIZED_SOURCE_CHANNEL,
    COUNT(*) AS RECORD_COUNT,
    COUNT(DISTINCT STANDARD_CHANNEL) AS STANDARD_CHANNEL_COUNT,
    COUNT(DISTINCT SOURCE_PLATFORM) AS PLATFORM_COUNT
FROM MARKETING_DB.RAW.CHANNEL_MAPPING_RAW
GROUP BY LOWER(TRIM(SOURCE_CHANNEL))
HAVING COUNT(DISTINCT STANDARD_CHANNEL) > 1
    OR COUNT(DISTINCT SOURCE_PLATFORM) > 1;

SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(
        EVENT_ID IS NULL OR TRIM(EVENT_ID) = ''
    ) AS MISSING_EVENT_ID,

    COUNT_IF(
        ORDER_ID IS NULL OR TRIM(ORDER_ID) = ''
    ) AS MISSING_ORDER_ID,

    COUNT_IF(
        USER_ID IS NULL OR TRIM(USER_ID) = ''
    ) AS MISSING_USER_ID,

    COUNT_IF(
        TRY_TO_TIMESTAMP_NTZ(CONVERSION_TIMESTAMP) IS NULL
    ) AS INVALID_TIMESTAMP,

    COUNT_IF(
        TRY_TO_DECIMAL(REVENUE_AMOUNT) IS NULL
    ) AS INVALID_REVENUE

FROM MARKETING_DB.RAW.CONVERSIONS_RAW;

