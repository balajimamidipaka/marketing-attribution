USING MARKETING_DB.RAW.CAMPAIGNS_UPLOAD_STAGING AS source
ON target.CAMPAIGN_ID = source.CAMPAIGN_ID

WHEN MATCHED THEN
    UPDATE SET
        target.CAMPAIGN_NAME = source.CAMPAIGN_NAME,
        target.SOURCE_PLATFORM = source.SOURCE_PLATFORM,
        target.CHANNEL = source.CHANNEL,
        target.BUDGET_AMOUNT = source.BUDGET_AMOUNT,
        target.BUDGET_CURRENCY = source.BUDGET_CURRENCY,
        target.START_DATE = source.START_DATE,
        target.END_DATE = source.END_DATE,
        target.CAMPAIGN_STATUS = source.CAMPAIGN_STATUS

WHEN NOT MATCHED THEN
    INSERT (
        CAMPAIGN_ID,
        CAMPAIGN_NAME,
        SOURCE_PLATFORM,
        CHANNEL,
        BUDGET_AMOUNT,
        BUDGET_CURRENCY,
        START_DATE,
        END_DATE,
        CAMPAIGN_STATUS
    )
    VALUES (
        source.CAMPAIGN_ID,
        source.CAMPAIGN_NAME,
        source.SOURCE_PLATFORM,
        source.CHANNEL,
        source.BUDGET_AMOUNT,
        source.BUDGET_CURRENCY,
        source.START_DATE,
        source.END_DATE,
        source.CAMPAIGN_STATUS
    );

