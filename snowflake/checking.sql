CREATE OR REPLACE TABLE MARKETING_DB.CLEANED.CONVERSION_REJECTS AS

WITH VALIDATION AS (
    SELECT
        *,
        CASE
            WHEN EVENT_ID IS NULL OR TRIM(EVENT_ID) = ''
                THEN 'MISSING_EVENT_ID'

            WHEN ORDER_ID IS NULL OR TRIM(ORDER_ID) = ''
                THEN 'MISSING_ORDER_ID'

            WHEN TRY_TO_TIMESTAMP_NTZ(CONVERSION_TIMESTAMP) IS NULL
                THEN 'INVALID_TIMESTAMP'

            WHEN TRY_TO_DECIMAL(REVENUE_AMOUNT, 12, 2) IS NULL
                 OR TRY_TO_DECIMAL(REVENUE_AMOUNT, 12, 2) < 0
                THEN 'INVALID_REVENUE'

            ELSE NULL
        END AS REJECTION_REASON
    FROM MARKETING_DB.RAW.CONVERSIONS_RAW
),

DUPLICATES AS (
    SELECT
        *,
        CASE
            WHEN REJECTION_REASON IS NOT NULL
                THEN REJECTION_REASON

            WHEN ROW_NUMBER() OVER (
                PARTITION BY ORDER_ID
                ORDER BY
                    TRY_TO_TIMESTAMP_NTZ(CONVERSION_TIMESTAMP),
                    EVENT_ID
            ) > 1
                THEN 'DUPLICATE_ORDER'

            ELSE NULL
        END AS FINAL_REJECTION_REASON
    FROM VALIDATION
)

SELECT *
FROM DUPLICATES
WHERE FINAL_REJECTION_REASON IS NOT NULL;

SELECT
    EVENT_ID,
    ORDER_ID,
    FINAL_REJECTION_REASON
FROM MARKETING_DB.CLEANED.CONVERSION_REJECTS
ORDER BY EVENT_ID;

SELECT
    (SELECT COUNT(*)
     FROM MARKETING_DB.RAW.CONVERSIONS_RAW) AS RAW_RECORDS,

    (SELECT COUNT(*)
     FROM MARKETING_DB.CLEANED.CONVERSIONS) AS CLEANED_RECORDS,

    (SELECT COUNT(*)
     FROM MARKETING_DB.CLEANED.CONVERSION_REJECTS)
        AS REJECTED_RECORDS,

    (SELECT COUNT(*)
     FROM MARKETING_DB.RAW.CONVERSIONS_RAW)
    -
    (SELECT COUNT(*)
     FROM MARKETING_DB.CLEANED.CONVERSIONS)
    -
    (SELECT COUNT(*)
     FROM MARKETING_DB.CLEANED.CONVERSION_REJECTS)
        AS UNACCOUNTED_RECORDS;