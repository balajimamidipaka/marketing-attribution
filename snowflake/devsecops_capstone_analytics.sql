CREATE OR REPLACE TABLE
MARKETING_DB.ANALYTICS.ATTRIBUTION_WINDOW_SENSITIVITY AS

WITH WINDOW_CONFIG AS (

    SELECT 1 AS CLICK_WINDOW_DAYS
    UNION ALL SELECT 7
    UNION ALL SELECT 14
    UNION ALL SELECT 30

),

CANDIDATE_TOUCHPOINTS AS (

    SELECT
        W.CLICK_WINDOW_DAYS,
        J.*

    FROM MARKETING_DB.ANALYTICS.CUSTOMER_JOURNEY J

    CROSS JOIN WINDOW_CONFIG W

),

CLICK_CHECK AS (

    SELECT

        *,

        MAX(
            IFF(
                INTERACTION_TYPE = 'CLICK'
                AND DAYS_BEFORE_CONVERSION <= CLICK_WINDOW_DAYS,
                1,
                0
            )
        ) OVER (
            PARTITION BY
                CLICK_WINDOW_DAYS,
                CONVERSION_EVENT_ID
        ) AS HAS_CLICK_IN_SELECTED_WINDOW

    FROM CANDIDATE_TOUCHPOINTS

),

ELIGIBLE_TOUCHPOINTS AS (

    SELECT *

    FROM CLICK_CHECK

    WHERE

        (
            INTERACTION_TYPE = 'CLICK'
            AND DAYS_BEFORE_CONVERSION <= CLICK_WINDOW_DAYS
        )

        OR

        (
            INTERACTION_TYPE IN ('VIEW', 'IMPRESSION')
            AND DAYS_BEFORE_CONVERSION <= 1
            AND HAS_CLICK_IN_SELECTED_WINDOW = 0
        )

),

RANKED_TOUCHPOINTS AS (

    SELECT

        *,

        ROW_NUMBER() OVER (
            PARTITION BY
                CLICK_WINDOW_DAYS,
                CONVERSION_EVENT_ID
            ORDER BY
                TOUCHPOINT_TIMESTAMP ASC,
                TOUCHPOINT_ID ASC
        ) AS FIRST_RANK,

        ROW_NUMBER() OVER (
            PARTITION BY
                CLICK_WINDOW_DAYS,
                CONVERSION_EVENT_ID
            ORDER BY
                TOUCHPOINT_TIMESTAMP DESC,
                TOUCHPOINT_ID DESC
        ) AS LAST_RANK,

        COUNT(*) OVER (
            PARTITION BY
                CLICK_WINDOW_DAYS,
                CONVERSION_EVENT_ID
        ) AS TOUCHPOINT_COUNT,

        POWER(
            2,
            -DAYS_BEFORE_CONVERSION / 7.0
        ) AS DECAY_WEIGHT,

        SUM(
            POWER(
                2,
                -DAYS_BEFORE_CONVERSION / 7.0
            )
        ) OVER (
            PARTITION BY
                CLICK_WINDOW_DAYS,
                CONVERSION_EVENT_ID
        ) AS TOTAL_DECAY_WEIGHT

    FROM ELIGIBLE_TOUCHPOINTS

)

