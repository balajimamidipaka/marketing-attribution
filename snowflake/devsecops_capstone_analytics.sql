CREATE OR REPLACE TABLE
MARKETING_DB.ANALYTICS.CHANNEL_PERFORMANCE AS

WITH SPEND_BY_CHANNEL AS
(
    SELECT
        UPPER(TRIM(C.CHANNEL)) AS STANDARD_CHANNEL,
        SUM(S.SPEND_AMOUNT) AS TOTAL_SPEND

    FROM MARKETING_DB.CLEANED.CAMPAIGN_SPEND S

    JOIN MARKETING_DB.CLEANED.CAMPAIGNS C
        ON S.CAMPAIGN_ID = C.CAMPAIGN_ID

    GROUP BY UPPER(TRIM(C.CHANNEL))
),

ATTRIBUTION_BY_CHANNEL AS
(
    SELECT
        STANDARD_CHANNEL,

        COUNT(DISTINCT CONVERSION_EVENT_ID)
            AS ATTRIBUTED_CONVERSIONS,

        SUM(ATTRIBUTED_REVENUE)
            AS ATTRIBUTED_REVENUE

    FROM MARKETING_DB.ANALYTICS.ATTRIBUTION_RESULTS

    WHERE MODEL_NAME = 'LAST_TOUCH'

    GROUP BY STANDARD_CHANNEL
)

SELECT
    S.STANDARD_CHANNEL,
    S.TOTAL_SPEND,

    COALESCE(A.ATTRIBUTED_CONVERSIONS, 0)
        AS ATTRIBUTED_CONVERSIONS,

    COALESCE(A.ATTRIBUTED_REVENUE, 0)
        AS ATTRIBUTED_REVENUE,

    ROUND(
        COALESCE(A.ATTRIBUTED_REVENUE, 0)
        / NULLIF(S.TOTAL_SPEND, 0),
        2
    ) AS ROAS,

    ROUND(
        S.TOTAL_SPEND
        / NULLIF(A.ATTRIBUTED_CONVERSIONS, 0),
        2
    ) AS CPA

FROM SPEND_BY_CHANNEL S

LEFT JOIN ATTRIBUTION_BY_CHANNEL A
    ON S.STANDARD_CHANNEL = UPPER(TRIM(A.STANDARD_CHANNEL));

