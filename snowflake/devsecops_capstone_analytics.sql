CREATE OR REPLACE TABLE
MARKETING_DB.ANALYTICS.BUDGET_PACING
(
    CAMPAIGN_ID VARCHAR(50),
    CAMPAIGN_NAME VARCHAR(150),
    REPORTING_DATE DATE,
    CAMPAIGN_BUDGET NUMBER(12,2),
    ACTUAL_SPEND NUMBER(12,2),
    EXPECTED_SPEND NUMBER(12,2),
    BUDGET_UTILIZATION NUMBER(10,2),
    PACING_PERCENTAGE NUMBER(10,2),
    PROJECTED_SPEND NUMBER(12,2),
    PACING_STATUS VARCHAR(30)
);

INSERT INTO MARKETING_DB.ANALYTICS.BUDGET_PACING

WITH REPORTING_DATE AS
(
    SELECT MAX(SPEND_DATE) AS REPORT_DATE
    FROM MARKETING_DB.CLEANED.CAMPAIGN_SPEND
),

CAMPAIGN_METRICS AS
(
    SELECT
        C.CAMPAIGN_ID,
        C.CAMPAIGN_NAME,
        R.REPORT_DATE,
        C.BUDGET_AMOUNT,
        C.START_DATE,
        C.END_DATE,

        COALESCE(SUM(
            CASE
                WHEN S.SPEND_DATE <= R.REPORT_DATE
                THEN S.SPEND_AMOUNT
                ELSE 0
            END
        ), 0) AS ACTUAL_SPEND

    FROM MARKETING_DB.CLEANED.CAMPAIGNS C

    CROSS JOIN REPORTING_DATE R

    LEFT JOIN MARKETING_DB.CLEANED.CAMPAIGN_SPEND S
        ON C.CAMPAIGN_ID = S.CAMPAIGN_ID
        AND S.SPEND_DATE BETWEEN C.START_DATE AND R.REPORT_DATE

    GROUP BY
        C.CAMPAIGN_ID,
        C.CAMPAIGN_NAME,
        R.REPORT_DATE,
        C.BUDGET_AMOUNT,
        C.START_DATE,
        C.END_DATE
),

PACING_CALCULATIONS AS
(
    SELECT
        *,
        DATEDIFF(DAY, START_DATE, END_DATE) + 1
            AS TOTAL_DAYS,

        GREATEST(
            0,
            DATEDIFF(
                DAY,
                START_DATE,
                LEAST(REPORT_DATE, END_DATE)
            ) + 1
        ) AS ELAPSED_DAYS

    FROM CAMPAIGN_METRICS
)

SELECT
    CAMPAIGN_ID,
    CAMPAIGN_NAME,
    REPORT_DATE,
    BUDGET_AMOUNT,
    ACTUAL_SPEND,

    ROUND(
        BUDGET_AMOUNT * ELAPSED_DAYS /
        NULLIF(TOTAL_DAYS, 0),
        2
    ) AS EXPECTED_SPEND,

    ROUND(
        ACTUAL_SPEND / NULLIF(BUDGET_AMOUNT, 0) * 100,
        2
    ) AS BUDGET_UTILIZATION,

    ROUND(
        ACTUAL_SPEND /
        NULLIF(
            BUDGET_AMOUNT * ELAPSED_DAYS /
            NULLIF(TOTAL_DAYS, 0),
            0
        ) * 100,
        2
    ) AS PACING_PERCENTAGE,

    ROUND(
        ACTUAL_SPEND * TOTAL_DAYS /
        NULLIF(ELAPSED_DAYS, 0),
        2
    ) AS PROJECTED_SPEND,

    CASE
        WHEN BUDGET_AMOUNT <= 0 THEN 'INVALID BUDGET'
        WHEN ELAPSED_DAYS = 0 THEN 'NOT STARTED'
        WHEN ACTUAL_SPEND /
            NULLIF(
                BUDGET_AMOUNT * ELAPSED_DAYS /
                NULLIF(TOTAL_DAYS, 0),
                0
            ) * 100 > 130 THEN 'CRITICAL'
        WHEN ACTUAL_SPEND /
            NULLIF(
                BUDGET_AMOUNT * ELAPSED_DAYS /
                NULLIF(TOTAL_DAYS, 0),
                0
            ) * 100 > 110 THEN 'WARNING'
        WHEN ACTUAL_SPEND /
            NULLIF(
                BUDGET_AMOUNT * ELAPSED_DAYS /
                NULLIF(TOTAL_DAYS, 0),
                0
            ) * 100 < 80 THEN 'UNDERSPENDING'
        ELSE 'ON TRACK'
    END AS PACING_STATUS

FROM PACING_CALCULATIONS;

