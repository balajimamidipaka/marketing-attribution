CREATE OR REPLACE TABLE CUSTOMER_JOURNEY AS

WITH MATCHED_TOUCHPOINTS AS (

    SELECT

        C.EVENT_ID AS CONVERSION_EVENT_ID,

        C.ORDER_ID,

        C.USER_ID,

        C.CONVERSION_TIMESTAMP,

        C.REVENUE_AMOUNT,

        C.CURRENCY AS CONVERSION_CURRENCY,

        T.TOUCHPOINT_ID,

        T.CAMPAIGN_ID,

        CMP.CAMPAIGN_NAME,

        T.SOURCE_CHANNEL,

        COALESCE(
            M.STANDARD_CHANNEL,
            'UNMAPPED'
        ) AS STANDARD_CHANNEL,

        T.INTERACTION_TYPE,

        T.TOUCHPOINT_TIMESTAMP,

        T.DEVICE_TYPE,

        DATEDIFF(
            'SECOND',
            T.TOUCHPOINT_TIMESTAMP,
            C.CONVERSION_TIMESTAMP
        ) / 86400.0 AS DAYS_BEFORE_CONVERSION,

        CASE
            WHEN T.INTERACTION_TYPE = 'CLICK'
             AND T.TOUCHPOINT_TIMESTAMP >=
                 DATEADD(DAY, -7, C.CONVERSION_TIMESTAMP)
            THEN TRUE
            ELSE FALSE
        END AS IS_WITHIN_CLICK_WINDOW_7D,

        CASE
            WHEN T.INTERACTION_TYPE IN ('IMPRESSION', 'VIEW')
             AND T.TOUCHPOINT_TIMESTAMP >=
                 DATEADD(DAY, -1, C.CONVERSION_TIMESTAMP)
            THEN TRUE
            ELSE FALSE
        END AS IS_WITHIN_VIEW_WINDOW_1D

    FROM MARKETING_DB.CLEANED.CONVERSIONS C

    INNER JOIN MARKETING_DB.CLEANED.TOUCHPOINTS T

        ON C.USER_ID = T.USER_ID

    LEFT JOIN MARKETING_DB.CLEANED.CAMPAIGNS CMP

        ON T.CAMPAIGN_ID = CMP.CAMPAIGN_ID

    LEFT JOIN MARKETING_DB.CLEANED.CHANNEL_MAPPING M

        ON LOWER(TRIM(T.SOURCE_CHANNEL))
         = LOWER(TRIM(M.SOURCE_CHANNEL))

    WHERE
        C.USER_ID IS NOT NULL

        AND T.TOUCHPOINT_TIMESTAMP
            <= C.CONVERSION_TIMESTAMP

        AND T.TOUCHPOINT_TIMESTAMP >=
            DATEADD(DAY, -30, C.CONVERSION_TIMESTAMP)
),

JOURNEY_WITH_CLICKS AS (

    SELECT *,

        MAX(
            IFF(IS_WITHIN_CLICK_WINDOW_7D, 1, 0)
        ) OVER (
            PARTITION BY CONVERSION_EVENT_ID
        ) AS HAS_ELIGIBLE_CLICK

    FROM MATCHED_TOUCHPOINTS
)

SELECT *,

    CASE

        WHEN IS_WITHIN_CLICK_WINDOW_7D = TRUE
        THEN TRUE

        WHEN HAS_ELIGIBLE_CLICK = 0
         AND IS_WITHIN_VIEW_WINDOW_1D = TRUE
        THEN TRUE

        ELSE FALSE

    END AS IS_ELIGIBLE_DEFAULT

FROM JOURNEY_WITH_CLICKS;


