    END), 4) AS FIRST_TOUCH_CREDIT,

    ROUND(SUM(CASE
        WHEN MODEL_NAME = 'LAST_TOUCH'
        THEN ATTRIBUTION_CREDIT ELSE 0
    END), 4) AS LAST_TOUCH_CREDIT,

    ROUND(SUM(CASE
        WHEN MODEL_NAME = 'LINEAR'
