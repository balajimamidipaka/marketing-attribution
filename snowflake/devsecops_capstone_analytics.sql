        ) = TOUCHPOINT_COUNT

        THEN REVENUE_AMOUNT - (
            ROUND(REVENUE_AMOUNT / TOUCHPOINT_COUNT, 2)
            * (TOUCHPOINT_COUNT - 1)
        )

        ELSE ROUND(REVENUE_AMOUNT / TOUCHPOINT_COUNT, 2)

    END

FROM RANKED_TOUCHPOINTS

UNION ALL

