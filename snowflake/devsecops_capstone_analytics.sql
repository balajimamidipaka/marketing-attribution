    FROM MARKETING_DB.CLEANED.CAMPAIGN_SPEND S

    JOIN MARKETING_DB.CLEANED.CAMPAIGNS C
        ON S.CAMPAIGN_ID = C.CAMPAIGN_ID

    GROUP BY UPPER(TRIM(C.CHANNEL))
),

MODEL_PERFORMANCE AS
(
    SELECT
        MODEL_NAME,
        UPPER(TRIM(STANDARD_CHANNEL)) AS STANDARD_CHANNEL,

        SUM(ATTRIBUTION_CREDIT)
            AS ATTRIBUTED_CONVERSIONS,

        SUM(ATTRIBUTED_REVENUE)
            AS ATTRIBUTED_REVENUE

    FROM MARKETING_DB.ANALYTICS.ATTRIBUTION_RESULTS

    GROUP BY
        MODEL_NAME,
        UPPER(TRIM(STANDARD_CHANNEL))
)

SELECT
    A.MODEL_NAME,
    A.STANDARD_CHANNEL,
    S.TOTAL_SPEND,

    ROUND(A.ATTRIBUTED_CONVERSIONS, 4)
        AS ATTRIBUTED_CONVERSIONS,

    A.ATTRIBUTED_REVENUE,

    ROUND(
        A.ATTRIBUTED_REVENUE /
        NULLIF(S.TOTAL_SPEND, 0),
        2
    ) AS ROAS

FROM MODEL_PERFORMANCE A

LEFT JOIN SPEND_BY_CHANNEL S
    ON A.STANDARD_CHANNEL = S.STANDARD_CHANNEL

ORDER BY
    A.STANDARD_CHANNEL,
    A.MODEL_NAME;


