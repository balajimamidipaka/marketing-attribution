INSERT INTO MARKETING_DB.ANALYTICS.ATTRIBUTION_RESULTS

WITH ELIGIBLE_TOUCHPOINTS AS (

    SELECT *

    FROM MARKETING_DB.ANALYTICS.CUSTOMER_JOURNEY

    WHERE IS_ELIGIBLE_DEFAULT = TRUE

),

RANKED_TOUCHPOINTS AS (

    SELECT

        *,

        ROW_NUMBER() OVER (
            PARTITION BY CONVERSION_EVENT_ID
            ORDER BY
                TOUCHPOINT_TIMESTAMP ASC,
                TOUCHPOINT_ID ASC
        ) AS FIRST_TOUCH_RANK,

        ROW_NUMBER() OVER (
            PARTITION BY CONVERSION_EVENT_ID
            ORDER BY
                TOUCHPOINT_TIMESTAMP DESC,
                TOUCHPOINT_ID DESC
        ) AS LAST_TOUCH_RANK,

        COUNT(*) OVER (
            PARTITION BY CONVERSION_EVENT_ID
        ) AS TOUCHPOINT_COUNT,

        POWER(
            2,
            -DAYS_BEFORE_CONVERSION / 7.0
        ) AS DECAY_WEIGHT,

        SUM(
            POWER(
                2,
                -DAYS_BEFORE_CONVERSION / 7.0
            )
        ) OVER (
            PARTITION BY CONVERSION_EVENT_ID
        ) AS TOTAL_DECAY_WEIGHT

    FROM ELIGIBLE_TOUCHPOINTS

)

