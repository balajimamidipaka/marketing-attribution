INSERT INTO MARKETING_DB.ANALYTICS.ATTRIBUTION_RESULTS

WITH RANKED_TOUCHPOINTS AS (

    SELECT
        *,

        ROW_NUMBER() OVER (
            PARTITION BY CONVERSION_EVENT_ID
            ORDER BY TOUCHPOINT_TIMESTAMP, TOUCHPOINT_ID
        ) AS TOUCHPOINT_RANK,

        COUNT(*) OVER (
            PARTITION BY CONVERSION_EVENT_ID
        ) AS TOUCHPOINT_COUNT

    FROM MARKETING_DB.ANALYTICS.CUSTOMER_JOURNEY

    WHERE IS_ELIGIBLE_DEFAULT = TRUE
),

CALCULATED_SHARES AS (

    SELECT
        *,

        ROUND(
            1::NUMBER(18,10) / TOUCHPOINT_COUNT,
            10
        ) AS BASE_CREDIT,

        ROUND(
            REVENUE_AMOUNT / TOUCHPOINT_COUNT,
            2
        ) AS BASE_REVENUE

    FROM RANKED_TOUCHPOINTS
)

SELECT

    'LINEAR' AS MODEL_NAME,

    CONVERSION_EVENT_ID,
    ORDER_ID,
    USER_ID,
    TOUCHPOINT_ID,
    CAMPAIGN_ID,
    STANDARD_CHANNEL,
    INTERACTION_TYPE,
    CONVERSION_TIMESTAMP,
    REVENUE_AMOUNT,
    CONVERSION_CURRENCY AS CURRENCY,

    CASE
        WHEN TOUCHPOINT_RANK = TOUCHPOINT_COUNT
        THEN 1.0 - (
            BASE_CREDIT * (TOUCHPOINT_COUNT - 1)
        )
        ELSE BASE_CREDIT
    END AS ATTRIBUTION_CREDIT,

    CASE
        WHEN TOUCHPOINT_RANK = TOUCHPOINT_COUNT
        THEN REVENUE_AMOUNT - (
            BASE_REVENUE * (TOUCHPOINT_COUNT - 1)
        )
        ELSE BASE_REVENUE
    END AS ATTRIBUTED_REVENUE

FROM CALCULATED_SHARES;

